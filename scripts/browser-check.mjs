import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:812},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await mkdir('.test-results',{recursive:true});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.locator('h1').waitFor();
await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
await page.locator('video').evaluate(async video=>{
 video.pause();video.currentTime=2;
 await new Promise(resolve=>video.addEventListener('seeked',resolve,{once:true}));
});
const poster=await page.locator('video').evaluate(video=>{const canvas=document.createElement('canvas');canvas.width=video.videoWidth;canvas.height=video.videoHeight;canvas.getContext('2d').drawImage(video,0,0);return canvas.toDataURL('image/jpeg',.9).split(',')[1];});
await writeFile('public/assets/images/hero-poster.jpg',Buffer.from(poster,'base64'));
await page.waitForTimeout(1200);
await page.screenshot({path:'.test-results/home-desktop.png'});
const assert=(condition,message)=>{if(!condition)throw new Error(message);console.log('PASS:',message);};
assert(await page.locator('h1').innerText()==='Intelligence that\nmoves business\nforward.','Hero text matches the reference');
await page.locator('header .logo').hover();await page.waitForTimeout(600);
assert(await page.locator('header .logo-name').evaluate(n=>Number(getComputedStyle(n).opacity)===1&&n.getBoundingClientRect().width>100),'Logo name reveals on hover');
await page.getByRole('button',{name:'Services',exact:true}).click();
await page.waitForTimeout(500);
assert(await page.locator('#services-menu').isVisible(),'Full-width Services menu opens');
assert(await page.locator('#services-menu li a').count()===18,'Mega menu contains all 18 service links');
assert(await page.evaluate(()=>document.body.style.overflow==='hidden'),'Background scroll is locked');
await page.screenshot({path:'.test-results/mega-menu-desktop.png'});
await page.keyboard.press('Escape');await page.waitForTimeout(350);
assert(await page.locator('#services-menu').count()===0,'Escape closes menu');
assert(await page.evaluate(()=>document.body.style.overflow!== 'hidden'),'Background scrolling restored');
await page.getByRole('button',{name:'Services',exact:true}).click();await page.getByRole('button',{name:'Services',exact:true}).click();await page.waitForTimeout(350);
assert(await page.locator('#services-menu').count()===0,'Services toggles menu closed');
await page.getByRole('button',{name:'Services',exact:true}).click();await page.waitForTimeout(350);
const panel=await page.locator('#services-menu').boundingBox();
await page.mouse.click(5,Math.min(800,panel.y+panel.height+15));await page.waitForTimeout(350);
assert(await page.locator('#services-menu').count()===0,'Click outside closes menu');
await page.locator('.image-card').first().scrollIntoViewIfNeeded();await page.locator('.image-card').first().hover();await page.waitForTimeout(600);
assert(await page.locator('.card-reveal').first().evaluate(n=>Number(getComputedStyle(n).opacity)===1),'Card details reveal on hover');
await page.screenshot({path:'.test-results/cards-desktop.png'});
await page.getByRole('tab',{name:/Build/}).click();
await page.getByRole('tabpanel').getByRole('heading',{name:'Bring the solution to life.'}).waitFor();
assert((await page.getByRole('tabpanel').innerText()).includes('Bring the solution to life.'),'Approach tabs change content');
await page.goto('http://127.0.0.1:5173/services.html');await page.getByRole('searchbox').fill('cloud');
assert(await page.locator('.catalog-card').count()===1,'Service search filters results');
await page.goto('http://127.0.0.1:5173/cloud.html');
assert(await page.locator('h1').innerText()==='A stronger foundation for every next move.','Service URLs render React detail pages');
await page.goto('http://127.0.0.1:5173/contact.html');
await page.getByLabel('Your name').fill('Preview Test');await page.getByLabel('Email address').fill('test@example.com');await page.getByLabel('How can we help?').fill('Testing the enquiry download behavior.');
const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Download enquiry'}).click();await downloadPromise;
assert((await page.getByRole('status').innerText()).includes('not been sent'),'Contact downloads honestly without a configured endpoint');
for(const width of [768,390]){
 await page.setViewportSize({width,height:844});await page.goto('http://127.0.0.1:5173/');await page.waitForTimeout(1100);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`No horizontal overflow at ${width}px`);
 await page.screenshot({path:`.test-results/home-${width}.png`});
 if(width===390)await page.getByRole('button',{name:/Menu/}).click();
 await page.getByRole('button',{name:'Services',exact:true}).click();await page.waitForTimeout(500);
 assert(await page.locator('#services-menu').isVisible(),`Menu works at ${width}px`);
 await page.screenshot({path:`.test-results/menu-${width}.png`});
 await page.keyboard.press('Escape');
}
await page.emulateMedia({reducedMotion:'reduce'});await page.goto('http://127.0.0.1:5173/');await page.waitForTimeout(600);
assert(await page.locator('video').evaluate(v=>v.paused),'Reduced motion disables automatic video playback');
assert(errors.length===0,`No browser runtime errors: ${errors.join('; ')}`);
await browser.close();
